#!/usr/bin/env node
/**
 * Generates src/data/exerciseImages.ts: a static require() map for the two frames of every
 * folder in assets/exercises. React Native can't require images by a runtime string, so this
 * file has to list them explicitly. Run after adding a folder: `node scripts/gen-exercise-images.js`
 *
 * Frames come from free-exercise-db (public domain): https://github.com/yuhonas/free-exercise-db
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'assets', 'exercises');
const ids = fs
  .readdirSync(dir)
  .filter((name) => fs.existsSync(path.join(dir, name, '0.jpg')) && fs.existsSync(path.join(dir, name, '1.jpg')))
  .sort();

const lines = ids.map(
  (id) => `  '${id}': [require('../../assets/exercises/${id}/0.jpg'), require('../../assets/exercises/${id}/1.jpg')],`,
);

fs.writeFileSync(
  path.join(root, 'src', 'data', 'exerciseImages.ts'),
  `// Generated by scripts/gen-exercise-images.js. Do not edit by hand.
import type { ImageSourcePropType } from 'react-native';

export const EXERCISE_IMAGES: Record<string, [ImageSourcePropType, ImageSourcePropType]> = {
${lines.join('\n')}
};
`,
);
console.log(`Wrote ${ids.length} exercises to src/data/exerciseImages.ts`);
